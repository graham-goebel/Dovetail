/* Site search: components first, then pages.

   Opens from any [data-open-search] button, from "/" or from Cmd/Ctrl+K. It
   is a sheet in the same style as Configure: a field at the top, results as
   rows under it, arrow keys to move, Enter to go, Escape to close. The index
   is assets/search-data.js, generated by tools/build-site.mjs with links from
   the site root, so this resolves them against the root the page links to. */

(function () {
  "use strict";

  var DATA = window.DovetailSearch || [];
  if (!DATA.length) return;

  var home = document.querySelector(".wordmark");
  var ROOT = home ? home.getAttribute("href").replace(/index\.html$/, "") : "";

  var bg, box, input, list, rows = [], active = 0, lastFocus = null;

  function esc(text) {
    return String(text).replace(/[&<>"]/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c];
    });
  }

  /* Name matches beat description matches; a match at the start of the name
     beats one in the middle; components beat pages on a tie. */
  function score(item, q) {
    var t = item.t.toLowerCase();
    var i = t.indexOf(q);
    if (t === q) return 100;
    if (i === 0) return 80 - t.length / 100;
    if (i > 0) return 60 - i;
    if ((item.s + " " + item.d).toLowerCase().indexOf(q) >= 0) return 20;
    return -1;
  }

  function results(q) {
    q = q.trim().toLowerCase();
    if (!q) return DATA.filter(function (x) { return x.k === "component"; }).slice(0, 12);
    return DATA.map(function (x) { return { x: x, n: score(x, q) + (x.k === "component" ? 0.5 : 0) }; })
      .filter(function (r) { return r.n >= 0; })
      .sort(function (a, b) { return b.n - a.n; })
      .slice(0, 30)
      .map(function (r) { return r.x; });
  }

  function paint() {
    var found = results(input.value);
    rows = [];
    list.innerHTML = "";
    if (!found.length) {
      list.innerHTML = '<p class="search-empty">Nothing matches “' + esc(input.value) + '”.</p>';
      return;
    }
    found.forEach(function (item, i) {
      var a = document.createElement("a");
      a.className = "search-row";
      a.href = ROOT + item.u;
      a.id = "search-opt-" + i;
      a.setAttribute("role", "option");
      a.innerHTML =
        '<span class="search-row-t">' + esc(item.t) + '</span>' +
        '<span class="search-row-s">' + esc(item.s) + '</span>' +
        (item.d ? '<span class="search-row-d">' + esc(item.d) + "</span>" : "");
      a.addEventListener("mousemove", function () { select(i); });
      list.appendChild(a);
      rows.push(a);
    });
    select(0);
  }

  function select(i) {
    if (!rows.length) return;
    active = (i + rows.length) % rows.length;
    rows.forEach(function (r, n) { r.setAttribute("aria-selected", n === active ? "true" : "false"); });
    input.setAttribute("aria-activedescendant", rows[active].id);
    rows[active].scrollIntoView({ block: "nearest" });
  }

  function build() {
    bg = document.createElement("div");
    bg.className = "search-bg";
    bg.hidden = true;
    bg.innerHTML =
      '<div class="search-sheet" role="dialog" aria-modal="true" aria-label="Search">' +
      '<div class="search-field">' +
      '<svg viewBox="0 0 24 24" width="18" height="18" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" aria-hidden="true"><path d="M10.5 17.5a7 7 0 1 0 0-14 7 7 0 0 0 0 14Z"/><path d="m20.5 20.5-5-5"/></svg>' +
      '<input type="search" placeholder="Search components and pages" autocomplete="off" spellcheck="false" role="combobox" aria-expanded="true" aria-controls="search-list" aria-label="Search">' +
      '<button type="button" class="search-close">Cancel</button>' +
      "</div>" +
      '<div class="search-list" id="search-list" role="listbox" aria-label="Results"></div>' +
      "</div>";
    document.body.appendChild(bg);
    box = bg.firstChild;
    input = bg.querySelector("input");
    list = bg.querySelector(".search-list");

    input.addEventListener("input", paint);
    input.addEventListener("keydown", function (e) {
      if (e.key === "ArrowDown") { e.preventDefault(); select(active + 1); }
      else if (e.key === "ArrowUp") { e.preventDefault(); select(active - 1); }
      else if (e.key === "Enter" && rows[active]) { e.preventDefault(); location.href = rows[active].href; }
    });
    bg.querySelector(".search-close").addEventListener("click", close);
    bg.addEventListener("mousedown", function (e) { if (e.target === bg) close(); });
  }

  function open() {
    if (!bg) build();
    lastFocus = document.activeElement;
    bg.hidden = false;
    document.body.classList.add("search-open");
    input.value = "";
    paint();
    input.focus();
  }

  function close() {
    if (!bg || bg.hidden) return;
    bg.hidden = true;
    document.body.classList.remove("search-open");
    if (lastFocus && lastFocus.focus) lastFocus.focus();
  }

  document.addEventListener("click", function (e) {
    var t = e.target.closest && e.target.closest("[data-open-search]");
    if (!t) return;
    e.preventDefault();
    open();
  });

  /* The Builder has a search and shortcuts of its own (Ctrl+Alt+K makes a
     component; / finds a component), so the site's keys stay out of its way. */
  var builderPage = !!document.getElementById("builder");
  document.addEventListener("keydown", function (e) {
    if (e.key === "Escape" && bg && !bg.hidden) { e.preventDefault(); close(); return; }
    if (builderPage || e.altKey) return;
    var typing = /^(INPUT|TEXTAREA|SELECT)$/.test((e.target && e.target.tagName) || "") || (e.target && e.target.isContentEditable);
    if ((e.key === "k" && (e.metaKey || e.ctrlKey)) || (e.key === "/" && !typing)) {
      e.preventDefault();
      open();
    }
  });

  window.DovetailSiteSearch = { open: open, close: close };
})();
